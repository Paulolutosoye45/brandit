export type Translate = (en: string, vars?: Record<string, string | number>) => string;

/** A function that returns the Pidgin for an English sentence, or the English itself when there is none (or the language is English). */
export function translator(lang: Lang): Translate {
  return (en, vars) => {
    const base = lang === 'pcm' ? (PIDGIN_UI[en] ?? en) : en;
    return vars ? base.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m)) : base;
  };
}
